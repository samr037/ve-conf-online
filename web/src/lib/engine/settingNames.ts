export function settingNamed(name: string): number | undefined {
  const i = settings.indexOf(name)
  if (i >= 0) return i
  const j = settings.indexOf('@' + name)
  return j >= 0 ? j : undefined
}

export function flagNamed(name: string): number | undefined {
  const i = flags.indexOf(name)
  if (i >= 0) return i
  const j = flags.indexOf('@' + name)
  return j >= 0 ? j : undefined
}
